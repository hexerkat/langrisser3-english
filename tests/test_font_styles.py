"""test_font_styles.py: the patcher's font selector (v0.9).

Two styles of 8x16 Latin art, chosen at build time (`build.py --font`):
  dosv  (default) DOS/V ANK16, the half-width font closest to the JP game's
        own Latin glyphs (user choice 2026-10-23, ranked by shape match).
  eagle Eagle III, the art of every release up to v0.8.
Only pixels change between styles. The half-glyph alphabet (its keys) and
so the bigram layout, the encoder maps, the band, the code caves and every
JP-preserved tile stay identical.

Red state (2026-10-23): font_tools has no styles; generate_english_font
takes no style and always draws Eagle III.
"""
import hashlib
import os
import sys
from pathlib import Path

import pytest

PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT / "tools"))
sys.path.insert(0, str(PROJECT))

import font_tools as ft  # noqa: E402

# Font generated by main at 1d14451..d2016a9 (Eagle III, v0.8.0 art).
EAGLE_FONT_SHA256 = (
    "02e04cbd33573687326683a3fe214c0a36795c57ed6ae91fae687c19a6237bb3")
BASELINE_ROW = 12


@pytest.fixture(scope="module")
def jp_font():
    jp_dir = os.environ.get("LANG3_JP_DIR")
    if not jp_dir:
        pytest.skip("LANG3_JP_DIR not set")
    from iso_tools import build_file_index, extract_file_data
    img = sorted(Path(jp_dir).glob("*rack*01*.bin"))[0].read_bytes()
    e = build_file_index(img)["LANG/FONT.BIN"]
    return extract_file_data(img, e.extent, e.size)


@pytest.fixture(scope="module")
def fonts(jp_font):
    prev = ft.ACTIVE_FONT_STYLE
    out = {name: ft.generate_english_font(jp_font, style=name)
           for name in ft.FONT_STYLES}
    ft.apply_style(prev)
    return out


def _tile(font, t):
    return font[t * 32:(t + 1) * 32]


def test_styles_offered():
    assert set(ft.FONT_STYLES) == {"dosv", "eagle"}
    assert ft.DEFAULT_FONT_STYLE == "dosv"


def test_eagle_style_is_the_shipped_font(fonts):
    assert hashlib.sha256(fonts["eagle"]).hexdigest() == EAGLE_FONT_SHA256


def test_styles_have_the_same_alphabet():
    keys, prev = {}, ft.ACTIVE_FONT_STYLE
    for name in ft.FONT_STYLES:
        ft.apply_style(name)
        keys[name] = (set(ft.HALF_GLYPHS), set(ft.HANKAKU_HALF_GLYPHS),
                      dict(ft.BIGRAM_TILE_MAP), dict(ft.CHAR_TILE_MAP))
    ft.apply_style(prev)
    assert keys["dosv"] == keys["eagle"]


def test_non_art_tiles_identical_across_styles(fonts):
    """Code caves, JP-preserved glyphs, engine glue and hand-drawn shared art
    do not depend on the style."""
    from balloon_zenkaku_cave import CAVE_TILE
    from width_class import WIDTH_CAVE_TILE
    shared = ({0, 43, 44, 45, 906, 1470, 1488, 1489, 1490,
               ft.NAKAGURO_TILE, CAVE_TILE, WIDTH_CAVE_TILE}
              | set(ft._FORMATION_GLYPH_TILES.values()) | ft.CAVE_BLOCK)
    for t in sorted(shared):
        assert _tile(fonts["dosv"], t) == _tile(fonts["eagle"], t), t


def test_dosv_art_reaches_every_latin_surface(fonts):
    import font_style_dosv as dosv
    f = fonts["dosv"]
    blank = bytes(16)
    for ch, half in {**dosv.LETTERS, **dosv.DIGITS, **dosv.UMLAUTS,
                     **dosv.UMLAUTS_UPPER}.items():
        t = ft.HANKAKU_TILE_MAP.get(ch)
        if t is not None:
            assert _tile(f, t) == ft._interleave(half, blank), ch
    for i, d in enumerate("0123456789"):
        assert _tile(f, 7 + i) == ft._render_glyph_centered(dosv.DIGITS[d])
    for i in range(26):
        ch = chr(65 + i)
        assert _tile(f, 17 + i) == ft._render_glyph_centered(dosv.LETTERS[ch])
    a, b = "D", "i"
    t = ft.BIGRAM_TILE_MAP[(a, b)]
    assert _tile(f, t) == ft._interleave(dosv.LETTERS[a], dosv.LETTERS[b])


def test_dosv_sits_on_the_shared_baseline():
    import font_style_dosv as dosv
    rows = [r for r in range(16) if dosv.LETTERS["x"][r]]
    assert rows[-1] == BASELINE_ROW
    period = [r for r in range(16) if dosv.PUNCT["."][r]]
    ellipsis = [r for r in range(16)
                if any(ft._ELLIPSIS_TILE_DATA[r * 2:r * 2 + 2])]
    assert period == ellipsis


def test_dosv_art_is_the_ttf_rendering():
    """The stored bytes are exactly what the generator draws from the TTF."""
    pytest.importorskip("PIL")
    import font_style_dosv as dosv
    import font_style_generate as gen
    ttf = gen.STYLES["dosv"]["ttf"]
    assert hashlib.sha256(ttf.read_bytes()).hexdigest() == dosv.TTF_SHA256
    assert gen.module_source("dosv") == \
        (PROJECT / "tools/font_style_dosv.py").read_text()


def test_build_offers_the_font_option():
    import build
    args = build.build_arg_parser().parse_args([])
    assert args.font == "dosv"
    args = build.build_arg_parser().parse_args(["--font", "eagle"])
    assert args.font == "eagle"


def test_launcher_passes_the_font():
    import launcher_core as lc
    args = lc.build_args(Path("/disc"), False, font="eagle")
    assert args[args.index("--font") + 1] == "eagle"


def test_launcher_choices_match_the_styles():
    """The patcher window offers exactly the build's styles, same default."""
    import launcher_core as lc
    assert [k for k, _label in lc.FONT_CHOICES] == ["dosv", "eagle"]
    assert set(k for k, _label in lc.FONT_CHOICES) == set(ft.FONT_STYLES)
    assert lc.DEFAULT_FONT == ft.DEFAULT_FONT_STYLE
