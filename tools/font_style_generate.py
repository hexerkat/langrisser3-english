#!/usr/bin/env python3
"""tools/font_style_generate.py: regenerate a font style's 8x16 art from a TTF.

Development tool, needs Pillow. The build never imports it: the build reads
the bytes this script writes into `tools/font_style_<name>.py` (stdlib only).

    python3 tools/font_style_generate.py dosv > tools/font_style_dosv.py

Each glyph is rasterized from the TTF's embedded 8x16 bitmap (FreeType MONO at
size 16) and moved vertically so the style's baseline (bottom row of 'x')
lands on row 12, the baseline of the Eagle III art. The shared tiles drawn
for Eagle (ellipsis 906, double quote 1470, the bullet, the name-entry
arrows) sit on that baseline, so every style must too.

Only the characters in STYLE_CHARS come from the TTF. The rest of the
half-glyph alphabet (space, '"', '•') is shared art in font_tools, so both
styles have the same key set and therefore the same tile layout.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE_ROW = 12

STYLES = {
    "dosv": {
        "ttf": ROOT / "data/fonts/Mx437_DOS-V_re_ANK16.ttf",
        "title": "DOS/V ANK16 (VileR re-creation of the IBM DOS/V Japanese "
                 "half-width font), closest to the JP game's Latin glyphs",
    },
}

LETTERS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
DIGITS = "0123456789"
PUNCT = ":;,.?!"
EXTRA_PUNCT = "-+()/*%[]'&"
UMLAUTS = "äöü"
UMLAUTS_UPPER = "ÄÖÜ"
STYLE_CHARS = LETTERS + DIGITS + PUNCT + EXTRA_PUNCT + UMLAUTS + UMLAUTS_UPPER


def _raster(font, ch):
    from PIL import Image, ImageDraw
    im = Image.new("1", (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=1)
    return [sum(im.getpixel((c, r)) << (7 - c) for c in range(8))
            for r in range(16)]


def render_style(name):
    from PIL import ImageFont
    font = ImageFont.truetype(str(STYLES[name]["ttf"]), 16)
    x = _raster(font, "x")
    shift = max(r for r in range(16) if x[r]) - BASELINE_ROW
    glyphs = {}
    for ch in STYLE_CHARS:
        rows = _raster(font, ch)
        if not any(rows):
            raise ValueError(f"{name}: no glyph for {ch!r}")
        lost = rows[:shift] if shift > 0 else rows[16 + shift:]
        if any(lost):
            raise ValueError(f"{name}: {ch!r} clipped by the baseline shift")
        moved = rows[shift:] + [0] * shift if shift > 0 else \
            [0] * -shift + rows[:16 + shift]
        glyphs[ch] = bytes(moved)
    return glyphs


def _dict_literal(var, chars, glyphs):
    lines = [f"{var} = {{"]
    for ch in chars:
        lines.append(f"    {ch!r}: bytes.fromhex('{glyphs[ch].hex()}'),")
    lines.append("}")
    return "\n".join(lines)


def module_source(name):
    style = STYLES[name]
    ttf = style["ttf"]
    glyphs = render_style(name)
    sha = hashlib.sha256(ttf.read_bytes()).hexdigest()
    parts = [
        f'"""tools/font_style_{name}.py: GENERATED by tools/font_style_generate.py.',
        "",
        f"{style['title']}.",
        f"Source: data/fonts/{ttf.name} (see data/fonts/SOURCES.md).",
        "Do not edit by hand: regenerate with",
        f"    python3 tools/font_style_generate.py {name} > tools/font_style_{name}.py",
        '"""',
        "",
        f"TTF_NAME = {ttf.name!r}",
        f"TTF_SHA256 = {sha!r}",
        "",
        _dict_literal("LETTERS", LETTERS, glyphs),
        "",
        _dict_literal("DIGITS", DIGITS, glyphs),
        "",
        _dict_literal("PUNCT", PUNCT, glyphs),
        "",
        _dict_literal("EXTRA_PUNCT", EXTRA_PUNCT, glyphs),
        "",
        _dict_literal("UMLAUTS", UMLAUTS, glyphs),
        "",
        _dict_literal("UMLAUTS_UPPER", UMLAUTS_UPPER, glyphs),
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in STYLES:
        sys.exit(f"usage: {sys.argv[0]} {{{','.join(STYLES)}}}")
    sys.stdout.write(module_source(sys.argv[1]))
